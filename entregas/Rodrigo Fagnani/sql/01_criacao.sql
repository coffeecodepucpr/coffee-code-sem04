CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    telefone TEXT,
    tipo TEXT NOT NULL CHECK (tipo IN ('cliente', 'profissional', 'ambos')),
    criado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE categorias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL UNIQUE,
    descricao TEXT,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE profissionais_categorias (
    profissional_id BIGINT NOT NULL
        REFERENCES usuarios(id) ON DELETE RESTRICT,
    categoria_id BIGINT NOT NULL
        REFERENCES categorias(id) ON DELETE RESTRICT,
    PRIMARY KEY (profissional_id, categoria_id)
);

CREATE TABLE solicitacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL
        REFERENCES usuarios(id) ON DELETE RESTRICT,
    profissional_id BIGINT NOT NULL
        REFERENCES usuarios(id) ON DELETE RESTRICT,
    categoria_id BIGINT NOT NULL
        REFERENCES categorias(id) ON DELETE RESTRICT,
    descricao TEXT NOT NULL,
    status TEXT NOT NULL CHECK (
        status IN ('solicitada', 'em_andamento', 'concluida', 'cancelada')
    ),
    criado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT solicitacao_cliente_diferente_profissional
        CHECK (cliente_id <> profissional_id)
);

CREATE TABLE avaliacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitacao_id BIGINT NOT NULL UNIQUE
        REFERENCES solicitacoes(id) ON DELETE CASCADE,
    nota SMALLINT NOT NULL CHECK (nota BETWEEN 1 AND 5),
    comentario TEXT,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);

ALTER TABLE usuarios ENABLE ROW LEVEL SECURITY;
ALTER TABLE categorias ENABLE ROW LEVEL SECURITY;
ALTER TABLE profissionais_categorias ENABLE ROW LEVEL SECURITY;
ALTER TABLE solicitacoes ENABLE ROW LEVEL SECURITY;
ALTER TABLE avaliacoes ENABLE ROW LEVEL SECURITY;
